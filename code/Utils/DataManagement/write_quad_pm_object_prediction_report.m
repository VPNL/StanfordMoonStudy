function reportTbl = write_quad_pm_object_prediction_report(tbl, lme, reportFile, opts)
% write_quad_pm_object_prediction_report
% Write a sorted object-level PM summary and 3-factor model prediction report.
%
% reportTbl = write_quad_pm_object_prediction_report(tbl, lme, reportFile, opts)
%
% Inputs
%   tbl        : Quad PM table with Measurement, ID, Real_Visual_Angle,
%                Distance, Elevation, Ratio_Visual_Angle, and log2 predictor
%                columns used by the fitted model.
%   lme        : fitted 3-factor LinearMixedModel.
%   reportFile : output text file.
%   opts       : optional metadata struct with ReportTitle, GeneratedBy,
%                SourceFile, ModelLabel.
%
% Output
%   reportTbl  : object-level table sorted by Mean_PM ascending.

if nargin < 4 || isempty(opts)
    opts = struct();
end

requiredVars = {'Measurement','ID','Real_Visual_Angle','Distance','Elevation','Ratio_Visual_Angle'};
missing = setdiff(requiredVars, tbl.Properties.VariableNames);
if ~isempty(missing)
    error('tbl is missing required variable(s): %s', strjoin(missing, ', '));
end

predictedPM = local_predict_pm_from_fixed_effects(tbl, lme);
measurement = string(tbl.Measurement);
[G, measurementLevels] = findgroups(measurement);
nGroups = numel(measurementLevels);

object = strings(nGroups, 1);
visualAngle = nan(nGroups, 1);
distance = nan(nGroups, 1);
elevation = nan(nGroups, 1);
nParticipants = nan(nGroups, 1);
meanPM = nan(nGroups, 1);
predictedPM3Factor = nan(nGroups, 1);

for iGroup = 1:nGroups
    idx = G == iGroup;
    object(iGroup) = local_measurement_to_object(measurementLevels(iGroup));
    visualAngle(iGroup) = mean(tbl.Real_Visual_Angle(idx), 'omitnan');
    distance(iGroup) = mean(tbl.Distance(idx), 'omitnan');
    elevation(iGroup) = mean(tbl.Elevation(idx), 'omitnan');
    nParticipants(iGroup) = numel(unique(string(tbl.ID(idx))));
    meanPM(iGroup) = mean(tbl.Ratio_Visual_Angle(idx), 'omitnan');
    predictedPM3Factor(iGroup) = mean(predictedPM(idx), 'omitnan');
end

reportTbl = table(object, visualAngle, distance, elevation, nParticipants, meanPM, predictedPM3Factor, ...
    'VariableNames', {'Object','Visual_Angle','Distance','Elevation','N_Participants','Mean_PM','Predicted_PM_3Factor'});
reportTbl = sortrows(reportTbl, {'Mean_PM','Object'}, {'ascend','ascend'});

if nargin < 3 || isempty(reportFile)
    return
end

reportFile = char(string(reportFile));
[reportDir,~,~] = fileparts(reportFile);
if ~isempty(reportDir) && ~exist(reportDir, 'dir')
    mkdir(reportDir);
end

[fid, msg] = fopen(reportFile, 'w');
if fid == -1
    error('Could not open report file %s: %s', reportFile, msg);
end
cleanupObj = onCleanup(@() fclose(fid));

reportTitle = local_get_opt(opts, 'ReportTitle', 'Quad PM Object Prediction Summary');
fprintf(fid, '%s\n', char(string(reportTitle)));
fprintf(fid, '%s\n\n', repmat('=', 1, strlength(string(reportTitle))));
fprintf(fid, 'Generated: %s\n', char(string(datetime("now", "Format", "yyyy-MM-dd HH:mm:ss"))));
fprintf(fid, 'Generated by: %s\n', char(string(local_get_opt(opts, 'GeneratedBy', mfilename))));
fprintf(fid, 'Source CSV: %s\n', char(string(local_get_opt(opts, 'SourceFile', '<not specified>'))));
modelLabel = local_get_opt(opts, 'ModelLabel', '');
if strlength(string(modelLabel)) > 0
    fprintf(fid, 'Model label: %s\n', char(string(modelLabel)));
end
fprintf(fid, 'Sorted by: Mean_PM ascending\n\n');

fprintf(fid, 'Object-Level PM Summary\n');
fprintf(fid, '-----------------------\n');
fprintf(fid, 'Mean_PM is mean Ratio_Visual_Angle in the input table.\n');
fprintf(fid, 'Predicted_PM_3Factor is the fixed-effect prediction from the 3-factor model, averaged within object.\n\n');
write_plain_text_table(fid, reportTbl);
end

function predictedPM = local_predict_pm_from_fixed_effects(tbl, lme)
coefNames = lower(string(lme.CoefficientNames));
coefEst = double(lme.Coefficients.Estimate);

b0 = local_coef_value(coefNames, coefEst, ["(intercept)","intercept"]);
bVA = local_coef_value(coefNames, coefEst, "log2real_visual_angle");
bD = local_coef_value(coefNames, coefEst, "log2distance");
bE = local_coef_value(coefNames, coefEst, "log2elevation");

[log2VA, log2D, log2E] = local_log_predictors(tbl);
predictedLogPM = b0 + bVA .* log2VA + bD .* log2D + bE .* log2E;
predictedPM = 2.^predictedLogPM;
end

function [log2VA, log2D, log2E] = local_log_predictors(tbl)
if ismember('log2real_visual_angle', tbl.Properties.VariableNames)
    log2VA = tbl.log2real_visual_angle;
else
    log2VA = log2(tbl.Real_Visual_Angle);
end

if ismember('log2distance', tbl.Properties.VariableNames)
    log2D = tbl.log2distance;
else
    log2D = log2(tbl.Distance);
end

if ismember('log2elevation', tbl.Properties.VariableNames)
    log2E = tbl.log2elevation;
else
    log2E = log2(tbl.Elevation + 1);
end
end

function value = local_coef_value(coefNames, coefEst, targetNames)
targetNames = lower(string(targetNames));
idx = [];
for iTarget = 1:numel(targetNames)
    idx = find(coefNames == targetNames(iTarget), 1, 'first');
    if ~isempty(idx)
        break;
    end
end

if isempty(idx)
    value = 0;
else
    value = coefEst(idx);
end
end

function objectName = local_measurement_to_object(measurementName)
objectName = regexprep(char(string(measurementName)), '_(Perceptual|Adjusted)_VA$', '', 'ignorecase');
objectName = string(objectName);
end

function value = local_get_opt(opts, fieldName, defaultValue)
if isstruct(opts) && isfield(opts, fieldName) && ~isempty(opts.(fieldName))
    value = opts.(fieldName);
else
    value = defaultValue;
end
end
